"""After-flood mode: survey type, post tags, the three post buttons, export fields.
Usage: python3 tests/test_post.py <base_url> <outdir>"""
import sys, json, zipfile, os
from playwright.sync_api import sync_playwright
BASE, OUT = sys.argv[1], sys.argv[2]; os.makedirs(OUT, exist_ok=True)
checks=[]; errs=[]
def check(n,c,d=''): checks.append(bool(c)); print(('PASS ' if c else 'FAIL ')+n+(' — '+str(d) if d!='' else ''))
with sync_playwright() as p:
    b=p.chromium.launch(args=['--use-fake-ui-for-media-stream','--use-fake-device-for-media-stream'])
    c=b.new_context(viewport={'width':360,'height':740},device_scale_factor=2,geolocation={'latitude':16.6912,'longitude':74.2439,'accuracy':5},permissions=['geolocation','camera'],accept_downloads=True)
    pg=c.new_page(); pg.on('pageerror',lambda e:errs.append(str(e)))
    pg.goto(BASE+'/index.html'); pg.wait_for_timeout(800)
    pg.click('text=Grant Permissions')
    pg.evaluate("setInterval(()=>window.dispatchEvent(new DeviceOrientationEvent('deviceorientationabsolute',{alpha:270,beta:70,gamma:0,absolute:true})),60)")
    pg.click('.ph[data-ph=post]'); pg.fill('#pname','Kolhapur_After'); pg.screenshot(path=OUT+'/p1_session.png')
    pg.click('text=Start Survey'); pg.wait_for_timeout(2000)
    check('post buttons', pg.inner_text('#cc').replace('\n',' ').count('FLOOD MARK')==1 and 'NOT FLOODED' in pg.inner_text('#cc'))
    check('post chips', all(pg.locator('#tc-'+k).count()==1 for k in ['depth','damage','sev','debris','stay']) and pg.locator('#tc-flow').count()==0)
    pg.click('#tc-depth'); pg.wait_for_timeout(300)
    check('sheet shows mark height', 'flood mark height' in pg.inner_text('#ts-depth-title').lower() and not pg.is_visible('#ts-flow-sec'))
    pg.click('#ts-depth .opt:has-text("Waist")'); pg.click('#ts-damage .opt:has-text("House")'); pg.click('#ts-damage .opt:has-text("Road")')
    pg.click('#ts-sev .opt:has-text("Major")'); pg.click('#ts-debris .opt:has-text("Thick")'); pg.click('#ts-stay .opt:has-text("1–3 days")')
    pg.locator('#ts-damage-sec').scroll_into_view_if_needed(); pg.screenshot(path=OUT+'/p2_sheet.png')
    pg.click('#ts-btns-live button'); pg.wait_for_timeout(200); pg.screenshot(path=OUT+'/p3_camera.png')
    for k in ['flood_mark','damage','not_flooded']: pg.click(f'.cbtn[onclick*="{k}"]'); pg.wait_for_timeout(1100)
    pg.click('.tab[data-tab=data]'); pg.wait_for_timeout(500); pg.screenshot(path=OUT+'/p4_data.png')
    with pg.expect_download() as d: pg.click('text=📦 Export ZIP')
    z=zipfile.ZipFile(d.value.path()); pts=json.loads(z.read([n for n in z.namelist() if n.endswith('_points.geojson')][0]))
    pr=[f['properties'] for f in pts['features']]
    check('classes', [x['flood_class'] for x in pr]==['flood_mark','damage','not_flooded'], [x['flood_class'] for x in pr])
    check('was_flooded', [x['was_flooded'] for x in pr]==[True,True,False])
    check('phase + depth kind', pr[0]['survey_phase']=='post' and pr[0]['water_depth_kind']=='max_from_flood_mark' and pr[0]['water_depth_class']=='waist')
    check('damage fields', pr[1]['damage_type']=='house;road' and pr[1]['damage_severity']=='major' and pr[1]['debris_left']=='thick' and pr[1]['water_stayed']=='1to3d', pr[1]['damage_type'])
    check('not flooded: no mark, no mud', pr[2]['water_depth_class']=='none' and pr[2]['debris_left'] is None)
    check('no during-flood fields on post', pr[0]['flow'] is None and pr[0]['flooded_land_cover'] is None)
    d.value.save_as(OUT+'/post.zip')
    x=b.new_context(viewport={'width':1280,'height':800}).new_page(); x.on('pageerror',lambda e:errs.append(str(e)))
    x.goto(BASE+'/explorer.html'); x.wait_for_timeout(800); x.set_input_files('#file-in',OUT+'/post.zip'); x.wait_for_timeout(1500)
    x.select_option('#sel-col','wasflooded'); x.wait_for_timeout(200)
    check('explorer: was-flooded legend', 'Not flooded' in x.inner_text('#col-legend') and x.inner_text('#st-mark')=='1' and x.inner_text('#st-dmg')=='1', x.inner_text('#col-legend').replace(chr(10),' | '))
    x.evaluate("openViewer(captures.find(c=>c.cls==='damage'))"); x.wait_for_timeout(300)
    check('explorer: damage details', 'House, Road' in x.inner_text('#viewer-grid') and 'Major' in x.inner_text('#viewer-grid'))
    x.screenshot(path=OUT+'/p5_explorer.png')
    b.close()
print('page errors:', errs or 'none'); print(f'{sum(checks)}/{len(checks)} checks passed'); sys.exit(0 if all(checks) and not errs else 1)
